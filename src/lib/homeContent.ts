import { getImageById, type CatalogImage } from "@/lib/imageCatalog";

function pick(id: number): CatalogImage {
  const im = getImageById(id);
  if (!im) throw new Error(`homeContent: صورة #${id} غير موجودة في الكتالوج`);
  return im;
}

