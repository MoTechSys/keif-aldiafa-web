function pick(id: number): CatalogImage {
  const im = getImageById(id);
  if (!im) throw new Error(`servicesContent: صورة #${id} غير موجودة في الكتالوج`);
  if (im.decorative) throw new Error(`servicesContent: صورة #${id} زخرفية — لا تُستخدم في معرض خدمة`);
  return im;
}
