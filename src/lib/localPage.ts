function localServiceCards(cityKey: string, excludePath: string) {
  const ar = CITIES[cityKey].ar;
  const cards = Object.values(SERVICES)
    .map((s) => ({ href: `/${localSlug(s.slug, cityKey)}`, img: serviceCardImg(s.slug, cityKey), b: `${s.ar} ${ar}`, small: s.short }))
    .filter((x) => x.href !== excludePath);
  const intents = INTENT_PAGES.filter((p) => p.city === cityKey && `/${p.slug}` !== excludePath)
    .map((p) => ({ href: `/${p.slug}`, img: getImagesForPage(`/${p.slug}`)[0] ?? serviceCardImg("qahwajiin", cityKey), b: p.ar, small: p.short }));
  return [...cards, ...intents];
}

